import assert from 'node:assert/strict';
import { sctrSnapshot, sctrMonthPeriod } from '../lib/sctr';
const policy = { sctrStartsAt: '2026-10-01', sctrEndsAt: '2026-10-31' };
const at = (day: string) => sctrSnapshot(policy, 3, new Date(`${day}T12:00:00Z`));
assert.equal(at('2026-10-23').status, 'ACTIVE');
assert.equal(at('2026-10-24').status, 'EXPIRING');
assert.equal(at('2026-10-24').daysLeft, 7);
assert.equal(at('2026-10-24').remindOn, '2026-10-24');
assert.equal(at('2026-10-31').status, 'EXPIRING');
assert.equal(at('2026-10-31').daysLeft, 0);
assert.equal(at('2026-11-01').status, 'EXPIRED');
assert.equal(at('2026-09-30').status, 'UPCOMING');
assert.equal(sctrSnapshot(policy, 3, new Date('2026-11-01T04:59:59Z')).status, 'EXPIRING');
assert.equal(sctrSnapshot(policy, 3, new Date('2026-11-01T05:00:00Z')).status, 'EXPIRED');
assert.equal(sctrSnapshot(null, 3).status, 'UNCONFIGURED');
assert.deepEqual(sctrMonthPeriod('2028-02-15'), { sctrStartsAt: '2028-02-01', sctrEndsAt: '2028-02-29' });
assert.deepEqual(sctrMonthPeriod('2026-12-31', true), { sctrStartsAt: '2027-01-01', sctrEndsAt: '2027-01-31' });
assert.equal(sctrMonthPeriod('2026-01-31', true).sctrEndsAt, '2026-02-28');
console.log('PASS: 7-day boundary, inclusive expiry, Peru midnight, unconfigured/future coverage, leap February and year rollover.');
